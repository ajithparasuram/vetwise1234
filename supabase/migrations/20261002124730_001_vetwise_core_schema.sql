-- ============================================================
-- ID GENERATION SEQUENCES & FUNCTIONS
-- ============================================================

-- Sequence for client ID numbering
CREATE SEQUENCE IF NOT EXISTS client_id_seq START 1;

-- Function to generate the next client ID
CREATE OR REPLACE FUNCTION generate_client_id()
RETURNS text AS $$
DECLARE
  next_val bigint;
  formatted text;
BEGIN
  next_val := nextval('client_id_seq');
  formatted := 'VW-CL-' || lpad(next_val::text, 6, '0');
  RETURN formatted;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger function for clients: auto-generate client_id on INSERT
CREATE OR REPLACE FUNCTION set_client_id()
RETURNS trigger AS $$
BEGIN
  IF NEW.client_id IS NULL OR NEW.client_id = '' THEN
    NEW.client_id := generate_client_id();
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_set_client_id ON clients;
CREATE TRIGGER trg_set_client_id
  BEFORE INSERT ON clients
  FOR EACH ROW EXECUTE FUNCTION set_client_id();

-- Function to generate patient ID: VW-CL-XXXXXX-PXX
CREATE OR REPLACE FUNCTION generate_patient_id(client_ref text)
RETURNS text AS $$
DECLARE
  count_val integer;
BEGIN
  SELECT count(*) INTO count_val FROM patients WHERE patients.client_id = client_ref;
  RETURN client_ref || '-P' || lpad((count_val + 1)::text, 2, '0');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger function for patients: auto-generate patient_id on INSERT
CREATE OR REPLACE FUNCTION set_patient_id()
RETURNS trigger AS $$
BEGIN
  IF NEW.patient_id IS NULL OR NEW.patient_id = '' THEN
    NEW.patient_id := generate_patient_id(NEW.client_id);
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_set_patient_id ON patients;
CREATE TRIGGER trg_set_patient_id
  BEFORE INSERT ON patients
  FOR EACH ROW EXECUTE FUNCTION set_patient_id();

