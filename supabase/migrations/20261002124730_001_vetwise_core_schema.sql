/*
# VetWise Core Schema — Clients, Patients, Locations, Media, Breeding, Audit

## Overview
Creates the foundational database schema for VetWise veterinary practice management.
All tables use Supabase auth for row-level security. The app has a sign-in screen,
so policies are scoped to `authenticated` users with ownership checks.

## New Tables

1. **clients** — Client accounts with auto-generated unique Client IDs (VW-CL-000001 format)
   - client_id (unique, auto-generated by trigger)
   - user_id (links to auth.users, owner)
   - full_name, phone, email, address, city, state, pincode
   - status (Active/Pending/Suspended)
   - created_at, updated_at

2. **patients** — Animal/patient records with auto-generated Patient IDs linked to Client ID
   - patient_id (unique, auto-generated: VW-CL-000001-P01)
   - client_id (FK to clients)
   - name, species, custom_species, breed, sex
   - date_of_birth, estimated_age, weight, color, markings
   - microchip_number, identification_details, notes
   - allergies, existing_conditions, medical_history
   - vaccination_info, medications, special_requirements
   - status, created_at, updated_at

3. **client_locations** — GPS/service locations for clients
   - client_id (FK to clients)
   - label (Home, Work, etc.)
   - latitude, longitude, location_accuracy
   - address_line, locality, city, district, state, pincode
   - is_primary

4. **patient_media** — Photos and videos for patients with type labels
   - patient_id (FK to patients)
   - media_type (FACE, BODY, ADDITIONAL, CLINICAL, VIDEO)
   - storage_key (Supabase Storage path)
   - content_type, file_size
   - uploader_id, uploaded_at
   - caption/label

5. **breeding_records** — Breeding history and records
   - patient_id (FK to patients — the female/breeding animal)
   - partner_patient_id (optional FK to patients)
   - partner_details (text for external partners)
   - breeding_date, expected_date
   - number_of_offspring, breeding_outcome
   - veterinary_observations, notes
   - status (Planned, Active, Completed)

6. **audit_logs** — Audit trail for important actions
   - actor_id (auth uid)
   - action_type (client_created, patient_created, etc.)
   - entity_type, entity_id
   - details (JSONB)
   - created_at

## Sequences & Functions
- `client_id_seq` — Sequence for client ID generation
- `generate_client_id()` — Function to create VW-CL-XXXXXX format IDs
- `generate_patient_id()` — Function to create VW-CL-XXXXXX-PXX format IDs
- Triggers on clients and patients tables for auto-ID generation

## Security
- RLS enabled on ALL tables
- Clients can only see/modify their own data
- Doctors can see clients/patients assigned to them (via doctor_clients table)
- Admins can see all data
- All policies use auth.uid() for ownership checks

## Notes
1. The app currently runs in demo mode (no Supabase auth) with fallback to demo data.
   Policies use `TO anon, authenticated` so the anon-key client can operate in demo mode.
   When real auth is wired in, policies should be tightened to `TO authenticated` only.
2. Client IDs and Patient IDs are generated server-side by triggers — never client-side.
3. Breed is free-text to support arbitrary breed names.
4. Species supports "Other" with a custom_species field.
*/

